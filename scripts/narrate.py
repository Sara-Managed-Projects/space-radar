#!/usr/bin/env python3
"""Render every trip stop's words to speech, offline, and refuse when the files have drifted.

Spec 0069 (2026-10-03). Ivan: "Speech for trips (like in planetarium ...), we will need the best
free speech generator, we will regenerate all speeches and download them." So the voice is made
HERE, once, by a model whose licence lets the files ship (registry/narration.yaml says which and
why), and the browser only ever plays a file: nothing is synthesised on a visitor's device and
nothing is fetched before they turn sound on (spec 0035 req 1).

    python3 scripts/narrate.py --check                      # CI: no TTS, stdlib + PyYAML
    $VENV/bin/python scripts/narrate.py --models DIR        # render what is stale
    $VENV/bin/python scripts/narrate.py --models DIR --only to-the-edge/sirius --force
    $VENV/bin/python scripts/narrate.py --models DIR --audition OUT --voices bf_emma,bm_george

WHAT IS SPOKEN. The stop's card, as the visitor reads it: the title, then the body. The bodies are
written to follow their titles ("A rover driven from Earth" / "Nobody rode it."), so the body
alone is often a sentence with no subject. registry/narration.yaml may leave a title out
(`skip_title`) where the body repeats it, or replace a stop's words for the ear (`say`).

WRITTEN FOR THE EYE, READ FOR THE EAR. spoken() turns what a synthesiser trips on into words --
"109 389" (a thin-spaced number), "3 February 1966", "10 km", "0.12", "M87", "TRAPPIST-1" -- and
REFUSES a digit it does not know how to say, rather than leaving the model to guess. Names the
grapheme-to-phoneme step gets wrong are in the registry's `lexicon`, as phonemes.

ONE CLIP PER STOP, ONE CUE PER SENTENCE. Each sentence is synthesised on its own and the clip is
the sentences joined with pauses this script chooses, so the WebVTT timings are sample counts and
not an aligner's guess. Levelled to -16 LUFS (a gain and a peak limiter, encode() says why), then
Opus at 32 kbps mono and an AAC twin for a Safari that cannot decode Opus (audio/pick.js).

IDEMPOTENT BY HASH. A clip's hash is its spoken script, the voice, the speed, the engine's id and
the pauses. A stop whose hash is in the manifest and whose files are there is left alone; change a
card's words and --check fails until that one stop is rendered again.

The render needs: kokoro-onnx, misaki[en], soundfile, numpy, PyYAML, an ffmpeg with libopus, and
the two model files (kokoro-v1.0.onnx, voices-v1.0.bin) whose sha256 the registry records.
"""
