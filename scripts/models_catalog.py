#!/usr/bin/env python3
"""The catalog of the 3D models Space Radar made itself, for models.spaceradar.ai (internal plan round 2, section D).

    python3 scripts/models_catalog.py                       # write site/model/models.json (the viewer's index)
    python3 scripts/models_catalog.py --out FILE            # also write the full catalog (models-catalog.json) to FILE
    python3 scripts/models_catalog.py --check               # the index is current and every row builds; CI runs this

WHAT IS OURS. A `real_models` row of registry/models.yaml whose `kind` is `built-from-dimensions` (a shape built in code
from published numbers and photographs) or `derived-from-images` (a mesh generated from a public-domain picture with
TRELLIS, then repaired and completed in code): scripts/asset_pack.py OWN_MODEL_KINDS, the same rule the /assets/ page
uses. Rows with no `kind` are other people's files (NASA 3D Resources, the PDS shape models) and are never listed.

THE NASA-NAMED ROWS, CHECKED BY HAND on 2026-11-11 (HAND_CHECKED): eight rows of ours name NASA in their `source` for
more than a picture they were compared with. Each was read in full; every one is kept, because none has a NASA triangle
in its file:
  hubble        built in 1.3.0; NASA's Hubble (A) mesh was used for proportions only, "none of its triangles is in the file"
  hubble-sts31  derived from our `hubble` builder; NASA has no model of this configuration
  shuttle-rms   built from published numbers; NASA 3D Resources has no model of the arm
  msl-entry     built from published numbers; NASA has no model of the aeroshell
  cygnus, xrism, seasat   generated by TRELLIS from one or two public-domain NASA pictures, then repaired
  hitomi        XRISM's generated body plus Hitomi's own parts built in code
EXCLUDED is where a row goes if a later check finds someone else's geometry in a file of ours; it is empty today.

THE FULL CATALOG (--out) is what scripts/deploy.sh uploads to the models site's bucket (data/models-catalog.json),
where a put rebuilds every page: a new row here reaches models.spaceradar.ai on the next main-site deploy with no page
work. It carries, per model: id, name, class, mission, look, the honesty sentence, the dimensions with their source,
the reference credits, the licence (MIT, this repository's), the file with its bytes, kB, SHA-256 and the triangles
counted from the .glb, the NORAD ids parsed from `used_for`, the live link where there is an object on the map, the
day the file was added (git), the picture paths on the models site, and the downloads (GitHub raw, the forge as the
fallback). The date needs the git history: a shallow clone gives no date rather than a wrong one, and --check does not
compare dates, so CI's two-commit checkout passes.

THE INDEX (site/model/models.json, committed) is the small half the viewer page (site/model/index.html) reads to turn
?id= into a file: id, name, file. --check fails when it is stale: run this script after adding a row.
"""

