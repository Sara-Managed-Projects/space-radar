def overall_key_of(dims: dict, key: str | None = None) -> str:
    """The dimensions key `overall_of` took its number from ('' when it took none), so the page can name the row and its source."""
    metres, _what = overall_of(dims, key)
    if metres is None:
        return ""
    for k, _w in OVERALL_KEYS:
        if key and k != key:
            continue
        for it in dims["items"]:
            if it["key"] == k and it["unit"] == "m":
                vals = it["value"] if isinstance(it["value"], list) else [it["value"]]
                if any(isinstance(v, (int, float)) and not isinstance(v, bool) and float(v) == metres for v in vals):
                    return k
    return ""


def overall_of(dims: dict, key: str | None = None) -> tuple[float | None, str]:
    """(metres, 'span' | 'diameter' | 'length' | 'height' | 'width' | 'overall') of the craft itself: the largest of
    OVERALL_KEYS the row gives (or the one dimensions key the row's `overall:` names); (None, '') when it gives none."""
    have = {it["key"]: it["value"] for it in dims["items"] if it["unit"] == "m"}
    best: tuple[float, str] | None = None
    for k, what in OVERALL_KEYS:
        if key and k != key:
            continue
        v = have.get(k)
        if isinstance(v, list):
            v = max((x for x in v if isinstance(x, (int, float))), default=None)
        if isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0 and (best is None or v > best[0]):
            best = (float(v), what)
    return best if best else (None, "")


def size_band(metres: float | None) -> str:
    if metres is None:
        return ""
    for key, _name, top in SIZES:
        if metres < top:
            return key
    return SIZES[-1][0]


def largest_of(dims: dict) -> float | None:
    """The largest length in the table: only for the filter's band when a row names no overall dimension."""
    best = None
    for it in dims["items"]:
        if it["unit"] != "m":
            continue
        for v in it["value"] if isinstance(it["value"], list) else [it["value"]]:
            if isinstance(v, (int, float)) and v > 0 and (best is None or v > best):
                best = float(v)
    return best


def references_of(row: dict) -> list[dict]:
    """The pictures and pages the shape was compared with: who made them and under what licence (credits only)."""
    out = []
    for r in row.get("references") or []:
        if not isinstance(r, dict):
            continue
        out.append({k: str(r.get(k) or "") for k in ("title", "url", "credit", "licence", "use")})
    return out


def git_days(root: Path) -> tuple[dict[str, str], dict[str, str]]:
    """({site/models/<file>: the day it was first added}, {site/models/<file>: the day it last changed}), YYYY-MM-DD,
    from `git log --diff-filter=A` and `git log`, one call each for all files. ({}, {}) where git is not there. In a
    shallow clone the boundary commit looks as if it added everything it holds, so a day that comes from a boundary
    commit is left out (no date rather than the boundary's)."""
    def log(*extra: str) -> list[tuple[str, str, list[str]]]:
        out = subprocess.run(["git", "-C", str(root), "log", *extra, "--no-renames", "--format=@%H %as", "--name-only",
                              "--", "site/models"], capture_output=True, text=True, timeout=120, check=True).stdout
        commits, cur = [], None
        for line in out.splitlines():
            if line.startswith("@"):
                sha, _, d = line[1:].partition(" ")
                cur = (sha, d, [])
                commits.append(cur)
            elif line and cur:
                cur[2].append(line)
        return commits
    try:
        adds, changes = log("--diff-filter=A"), log()
        shallow_file = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-path", "shallow"],
                                      capture_output=True, text=True, timeout=10, check=True).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return {}, {}
    sf = Path(shallow_file) if Path(shallow_file).is_absolute() else root / shallow_file
    boundary = set(sf.read_text().split()) if sf.is_file() else set()
    added: dict[str, str] = {}
    for sha, d, paths in adds:  # newest first: the last day met is the first add
        for p in paths:
            added[p] = "" if sha in boundary else d
    changed: dict[str, str] = {}
    for sha, d, paths in changes:  # newest first: the first day met is the last change
        for p in paths:
            if p not in changed and sha not in boundary:
                changed[p] = d
    return added, changed


