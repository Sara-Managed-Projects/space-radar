# ---- the .glb ---------------------------------------------------------------------------------------------------

def glb_json(path: Path) -> dict:
    """The JSON chunk of a binary glTF (the header is 12 bytes; the first chunk is the JSON)."""
    with path.open("rb") as fh:
        head = fh.read(20)
        magic, _version, _length, clen, ctype = struct.unpack("<4sIIII", head)
        if magic != b"glTF" or ctype != 0x4E4F534A:
            raise ValueError(f"{path.name} is not a binary glTF")
        return json.loads(fh.read(clen).decode("utf-8"))


def glb_triangles(path: Path) -> int:
    """Triangles drawn by the default scene: each mesh counted once per node that places it (and per GPU instance).

    Counts come from the accessors, which glTF keeps uncompressed in the JSON even when the buffers are meshopt-
    compressed (EXT_meshopt_compression), so nothing needs decoding. Triangle strips and fans count n - 2."""
    g = glb_json(path)
    acc = g.get("accessors") or []

    def mesh_tris(mi: int) -> int:
        n = 0
        for p in (g["meshes"][mi].get("primitives") or []):
            mode = p.get("mode", 4)
            ref = p.get("indices", (p.get("attributes") or {}).get("POSITION"))
            if ref is None:
                continue
            c = acc[ref]["count"]
            n += c // 3 if mode == 4 else max(0, c - 2) if mode in (5, 6) else 0
        return n

    nodes = g.get("nodes") or []
    scenes = g.get("scenes") or []
    roots = scenes[g.get("scene", 0)]["nodes"] if scenes else range(len(nodes))
    total, stack, seen = 0, list(roots), 0
    while stack:
        ni = stack.pop()
        seen += 1
        if seen > 100000:  # a cycle is not valid glTF; never hang on one
            raise ValueError(f"{path.name}: node graph does not end")
        node = nodes[ni]
        if "mesh" in node:
            inst = ((node.get("extensions") or {}).get("EXT_mesh_gpu_instancing") or {}).get("attributes") or {}
            copies = acc[next(iter(inst.values()))]["count"] if inst else 1
            total += mesh_tris(node["mesh"]) * copies
        stack.extend(node.get("children") or [])
    return total


# ---- the row ----------------------------------------------------------------------------------------------------

def norad_ids(used_for: str) -> list[int]:
    """NORAD catalogue numbers the row's `used_for` names: after the word NORAD (one, or a list joined by commas and
    'and'), and five-digit numbers standing alone in brackets, which is how the GEO and constellation rows list them
    ("THURAYA-2 and THURAYA-3 (27825, 32404)"). Years and counts are four digits or fewer and never match the second."""
    text = str(used_for or "")
    out: list[int] = []
    for m in re.finditer(r"NORAD ((?:\d{1,6})(?:(?:,\s*|,? and |,? or )\d{1,6})*)", text):
        out += [int(x) for x in re.findall(r"\d{1,6}", m.group(1))]
    for m in re.finditer(r"\((\d{5}(?:(?:,\s*|,? and )\d{5})*)\)", text):
        out += [int(x) for x in re.findall(r"\d{5}", m.group(1))]
    seen: list[int] = []
    for n in out:
        if n not in seen:
            seen.append(n)
    return seen


def live_link(row: dict, norad: list[int]) -> str:
    """The object on the live map: the first NORAD number (#at=sat-N, the app's own link), else the deep-space record
    the row names (`deep-...` in data/sample.js); '' when nothing on the map is this model."""
    if norad:
        return f"{SITE}/#at=sat-{norad[0]}"
    m = re.search(r"`(deep-[a-z0-9-]+)`", str(row.get("used_for") or ""))
    return f"{SITE}/#at={m.group(1)}" if m else ""


def mission_of(row: dict) -> str:
    """The class decides for rockets, telescopes, probes and surface sites; satellites and stations are grouped by
    the first rule that matches their id, then their `used_for`; MISSION_OF names the few the words get wrong."""
    if row["id"] in MISSION_OF:
        return MISSION_OF[row["id"]]
    klass = row.get("class") or ""
    if klass in ("rocket", "telescope", "probe", "site"):
        return CLASS_MISSION[klass]
    text = f"{row['id']} {row.get('used_for') or ''}".lower()
    for key, _name, rx in MISSIONS:
        if re.search(rx, row["id"]):
            return key
    for key, _name, rx in MISSIONS:
        if re.search(rx, text):
            return key
    return CLASS_MISSION.get(klass, "technology")


def label_of(key: str) -> tuple[str, str]:
    """('Array length', 'm') from 'array_length_m'."""
    parts = key.split("_")
    unit = ""
    if len(parts) > 1 and parts[-1] in UNITS:
        unit = UNITS[parts.pop()]
    words = " ".join(parts).strip()
    return (words[:1].upper() + words[1:]) if words else key, unit


def dimensions_of(row: dict) -> dict:
    d = row.get("dimensions") or {}
    items = []
    for k, v in d.items():
        if k in ("source", "read"):
            continue
        label, unit = label_of(k)
        if isinstance(v, list):
            v = [x for x in v if isinstance(x, (int, float, str))]
        elif not isinstance(v, (int, float, str)):
            continue
        items.append({"key": k, "label": label, "value": v, "unit": unit})
    return {"items": items, "source": str(d.get("source") or ""), "read": str(d.get("read") or "")}


def size_of(dims: dict) -> tuple[float | None, str]:
    best = None
    for it in dims["items"]:
        if it["unit"] != "m":
            continue
        vals = it["value"] if isinstance(it["value"], list) else [it["value"]]
        for v in vals:
            if isinstance(v, (int, float)) and v > 0 and (best is None or v > best):
                best = float(v)
    if best is None:
        return None, ""
    for key, _name, top in SIZES:
        if best < top:
            return best, key
    return best, SIZES[-1][0]


def references_of(row: dict) -> list[dict]:
    """The pictures and pages the shape was compared with: who made them and under what licence (credits only)."""
    out = []
    for r in row.get("references") or []:
        if not isinstance(r, dict):
            continue
        out.append({k: str(r.get(k) or "") for k in ("title", "url", "credit", "licence", "use")})
    return out


def first_added(root: Path) -> dict[str, str]:
    """{site/models/<file>: the day it was first added, YYYY-MM-DD}: `git log --diff-filter=A`, one call for all
    files. {} where git is not there. In a shallow clone the boundary commit looks as if it added everything it
    holds, so a file whose first add IS a boundary commit gets no date rather than the boundary's."""
    try:
        out = subprocess.run(["git", "-C", str(root), "log", "--diff-filter=A", "--no-renames", "--format=@%H %as",
                              "--name-only", "--", "site/models"], capture_output=True, text=True, timeout=120,
                             check=True).stdout
        shallow_file = subprocess.run(["git", "-C", str(root), "rev-parse", "--git-path", "shallow"],
                                      capture_output=True, text=True, timeout=10, check=True).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return {}
    sf = Path(shallow_file) if Path(shallow_file).is_absolute() else root / shallow_file
    boundary = set(sf.read_text().split()) if sf.is_file() else set()
    day, seen = "", {}
    for line in out.splitlines():
        if line.startswith("@"):
            sha, _, d = line[1:].partition(" ")
            day = "" if sha in boundary else d
        elif line:
            seen[line] = day  # newest first: the last day met is the first add
    return seen


def pictures_of(mid: str) -> dict:
    """Paths on the models site (its media/ prefix), rendered once per file hash by the models site's tools."""
    base = f"media/{mid}"
    return {"hero": f"{base}/hero.webp", "thumb": f"{base}/thumb.webp",
            "angles": [f"{base}/angle-{i}.webp" for i in (1, 2, 3)], "share": f"{base}/share.jpg"}


def entry(row: dict, root: Path, added: dict[str, str]) -> dict:
    f = root / row["file"]
    fname = f.name
    data = f.read_bytes()
    norad = norad_ids(row.get("used_for"))
    dims = dimensions_of(row)
    size_m, band = size_of(dims)
    name = asset_pack.name_of(row["id"])
    return {
        "id": row["id"],
        "name": name,
        "class": row.get("class") or "",
        "mission": mission_of(row),
        "look": "pbr" if row.get("look") == "pbr" else "toon",
        "kind": row["kind"],
        "flagship": bool(row.get("flagship")),
        "honesty": str(row.get("honesty") or ""),
        "made": str(row.get("credit") or ""),
        "how": str(row.get("source") or ""),
        "used_for": str(row.get("used_for") or ""),
        "dimensions": dims,
        "size_m": size_m,
        "size": band,
        "references": references_of(row),
        "licence": dict(LICENCE, note=str(row.get("licence") or "")),
        "credit_line": f"{name} 3D model by Space Radar (spaceradar.ai), MIT License",
        "file": fname,
        "bytes": len(data),
        "kb": round(len(data) / 1024),
        "sha256": hashlib.sha256(data).hexdigest(),
        "triangles": glb_triangles(f),
        "budget_tris": row.get("budget_tris"),
        "norad": norad,
        "live": live_link(row, norad),
        "added": added.get(row["file"], ""),
        "modified": str(row.get("modified") or ""),
        "pictures": pictures_of(row["id"]),
        "viewer": f"{SITE}/model/?id={row['id']}",
        "page": f"{MODELS_SITE}/{row['id']}/",
        "downloads": {"glb": GITHUB_RAW + fname, "fallback": FORGE_RAW + fname},
    }


def rows(doc: dict | None = None) -> list[dict]:
    doc = doc if doc is not None else asset_pack._yml("models.yaml")
    return [r for r in doc.get("real_models") or []
            if isinstance(r, dict) and r.get("kind") in OWN_KINDS and r.get("id") not in EXCLUDED]


def catalog(root: Path = ROOT, doc: dict | None = None, with_dates: bool = True) -> dict:
    added = first_added(root) if with_dates else {}
    models = [entry(r, root, added) for r in rows(doc)]
    models.sort(key=lambda m: m["id"])
    return {
        "version": VERSION,
        "source": "registry/models.yaml real_models (scripts/models_catalog.py)",
        "count": len(models),
        "classes": [c for c in CLASSES if any(m["class"] == c for m in models)],
        "missions": [{"id": k, "name": n} for k, n in MISSION_NAMES.items() if any(m["mission"] == k for m in models)],
        "sizes": [{"id": k, "name": n} for k, n, _ in SIZES],
        "licence": LICENCE,
        "models": models,
    }


def index_of(cat: dict) -> dict:
    """The viewer's index: only what turning ?id= into a file needs."""
    return {"version": VERSION, "models": {m["id"]: {"name": m["name"], "file": m["file"]} for m in cat["models"]}}


def dumps(obj: dict, compact: bool = False) -> str:
    if compact:
        return json.dumps(obj, ensure_ascii=False, separators=(",", ":"), sort_keys=False) + "\n"
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def problems(cat: dict, doc: dict | None = None) -> list[str]:
    out = []
    doc = doc if doc is not None else asset_pack._yml("models.yaml")
    want = [r["id"] for r in rows(doc)]
    if len(want) != cat["count"]:
        out.append(f"{len(want)} rows of ours, {cat['count']} in the catalog")
    ids = set()
    for m in cat["models"]:
        if m["id"] in ids:
            out.append(f"{m['id']}: twice")
        ids.add(m["id"])
        if m["class"] not in CLASSES:
            out.append(f"{m['id']}: class {m['class']!r} is not one of {', '.join(CLASSES)}")
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", m["id"]):
            out.append(f"{m['id']}: the id is not a URL path segment")
        if m["triangles"] <= 0:
            out.append(f"{m['id']}: no triangles counted in {m['file']}")
        if not m["honesty"]:
            out.append(f"{m['id']}: no honesty sentence")
        if not m["dimensions"]["source"]:
            out.append(f"{m['id']}: the dimensions name no source")
    for mid in HAND_CHECKED:
        if mid not in ids and mid not in EXCLUDED:
            out.append(f"{mid}: hand-checked as ours but not in the catalog")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", help="write the full catalog (models-catalog.json) here")
    ap.add_argument("--check", action="store_true", help="the index is current and every row builds; writes nothing")
    a = ap.parse_args(argv)
    cat = catalog(with_dates=not a.check)
    bad = problems(cat)
    idx = dumps(index_of(cat), compact=True)
    if a.check:
        if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != idx:
            bad.append(f"{INDEX.relative_to(ROOT)} is stale: run python3 scripts/models_catalog.py")
        for b in bad:
            print(f"FAIL: {b}")
        if not bad:
            print(f"PASS: {cat['count']} models of ours, {sum(m['triangles'] for m in cat['models'])} triangles, "
                  f"the viewer's index is current")
        return 1 if bad else 0
    if bad:
        for b in bad:
            print(f"error: {b}", file=sys.stderr)
        return 1
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    INDEX.write_text(idx, encoding="utf-8")
    print(f"wrote {INDEX.relative_to(ROOT)} ({cat['count']} models)")
    if a.out:
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(dumps(cat), encoding="utf-8")
        dated = sum(1 for m in cat["models"] if m["added"])
        print(f"wrote {out} ({cat['count']} models, {dated} with the day they were added)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
