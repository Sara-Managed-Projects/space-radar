/** The language to speak: ?lang= first, then the browser's list; 'en' when neither names one of the eleven. Pure. */
export function pickWordsLanguage(search, preferred) {
  const base = (tag) => String(tag || '').toLowerCase().split(/[-_]/)[0];
  const asked = /[?&]lang=([^&#]*)/.exec(String(search || ''));
  if (asked) {
    let code = '';
    try { code = base(decodeURIComponent(asked[1])); } catch { /* a stray % */ }
    return Object.prototype.hasOwnProperty.call(WORDS, code) ? code : 'en';
  }
  for (const tag of preferred || []) {
    const code = base(tag);
    if (Object.prototype.hasOwnProperty.call(WORDS, code)) return code;
  }
  return 'en';
}

/** `fill('… {name} …', {name})`: a slot the words have and the values lack stays as it is (a test catches it). */
export const fill = (s, v = {}) => String(s).replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m));

/** Metres as the language writes them: one decimal under 10 m, whole metres above. */
export function metres(m, lang = 'en') {
  const digits = m < 10 ? 1 : 0;
  try {
    return new Intl.NumberFormat(LOCALES[lang] || 'en-GB', { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(m);
  } catch {
    return m.toFixed(digits);
  }
}
